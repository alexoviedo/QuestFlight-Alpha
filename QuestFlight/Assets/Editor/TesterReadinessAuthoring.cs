using System;
using System.IO;
using QuestFlight.Product;
using UnityEditor;
using UnityEngine;
using UnityEngine.Rendering;

namespace QuestFlight.Editor
{
    public static class TesterReadinessAuthoring
    {
        public static void RunBatch()
        {
            try
            {
                const string root="Assets/Production/UI/ReleasePolish";
                var world=PrefabUtility.LoadPrefabContents("Assets/Resources/QuestFlightLab/Production/ProductionWorldRoot.prefab");
                try
                {
                    var experience=world.GetComponentInChildren<ProductFlightExperience>(true);
                    var map=(GameObject)new SerializedObject(experience).FindProperty("mapRoot").objectReferenceValue;
                    var path=Line(map.transform,"FlownPath",new Color(.96f,.72f,.32f),root);
                    var route=Line(map.transform,"SelectedRoute",new Color(.35f,.77f,.93f),root);
                    var target=Line(map.transform,"LessonDestination",new Color(.35f,.77f,.93f),root);
                    experience.ConfigureMapLines(path,route,target);
                    foreach(var text in world.GetComponentsInChildren<TextMesh>(true))
                    {
                        if(text.name=="DemoFlightCardSubtitle")text.text="Tour and landing · 12–18 min · observe or take control";
                        if(text.name=="FreeFlightCardSubtitle")text.text="Fresh airport start · you fly · no time limit";
                        if(text.name=="LessonsCardSubtitle")text.text="Six guided exercises · begin with Cockpit and taxi";
                        ProductUiLabel.Sync(text);
                    }
                    PrefabUtility.SaveAsPrefabAsset(world,"Assets/Resources/QuestFlightLab/Production/ProductionWorldRoot.prefab");
                }
                finally {PrefabUtility.UnloadPrefabContents(world);}
                File.WriteAllText(root+"/TesterReadiness_SOURCE.md","# Tester readiness map overlays\nOriginal project-authored line geometry and solid-color materials, generated by TesterReadinessAuthoring. No external assets. Uses existing built-in Unlit/Color shader. Runtime modifies only positions on three explicitly serialized LineRenderers; no runtime hierarchy construction. Path is limited to 256 points; route uses the existing authored flight route. Original project work, same terms as project source.\n");
                AssetDatabase.SaveAssets();AssetDatabase.Refresh();
                QuestFlightLab.Editor.ProductionVisualQaBatchRunner.RunReleasePolishQa();
                Debug.Log("[TesterReadiness] Authored overlays and captured UI review.");
                EditorApplication.Exit(0);
            }
            catch(Exception e){Debug.LogException(e);EditorApplication.Exit(1);}
        }
        private static LineRenderer Line(Transform parent,string name,Color color,string root)
        {
            var child=parent.Find(name);
            if(child==null){var go=new GameObject(name);go.transform.SetParent(parent,false);child=go.transform;}
            var renderer=child.GetComponent<LineRenderer>();if(renderer==null)renderer=child.gameObject.AddComponent<LineRenderer>();
            string path=root+"/"+name+".mat";var material=AssetDatabase.LoadAssetAtPath<Material>(path);
            if(material==null){material=new Material(Shader.Find("Unlit/Color"));AssetDatabase.CreateAsset(material,path);}
            material.color=color;material.renderQueue=3511;EditorUtility.SetDirty(material);
            renderer.sharedMaterial=material;renderer.useWorldSpace=false;renderer.alignment=LineAlignment.TransformZ;
            renderer.widthMultiplier=.0022f;renderer.numCapVertices=0;renderer.numCornerVertices=0;renderer.positionCount=0;
            renderer.shadowCastingMode=ShadowCastingMode.Off;renderer.receiveShadows=false;return renderer;
        }
    }
}
